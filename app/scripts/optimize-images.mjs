#!/usr/bin/env node
/**
 * Batch photo optimiser for Happy Time Connect.
 *
 * Drop camera / phone originals (JPG, PNG, HEIC-converted, whatever) into
 *   app/raw-images/
 * then run, from the app folder:
 *   npm run images
 *
 * Every original becomes two WebP files in app/src/assets/products/:
 *   <name>.webp      960 px wide  – used on screens wider than 560 px
 *   <name>-480.webp  480 px wide  – used on phones
 *
 * The originals in raw-images/ are never committed (see .gitignore); only the
 * finished WebP files are, and those are what Vite fingerprints and serves.
 *
 * The file name matters: it must match the SKU of the product in the database.
 * "HT-W-214.jpg" -> "HT-W-214.webp" -> the tile for SKU HT-W-214 picks it up
 * automatically (see src/assets/products.js).
 */
import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const IN = path.join(ROOT, "raw-images");
const OUT = path.join(ROOT, "src/assets/products");

const SIZES = [
  { suffix: "", width: 960, quality: 68 },
  { suffix: "-480", width: 480, quality: 72 }
];
const ACCEPTED = new Set([".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff", ".avif"]);

const kB = n => `${Math.round(n / 1024)} kB`;

function safeName(file) {
  // Keep SKUs readable and case-sensitive-looking, only strip unsafe characters.
  const base = path.basename(file, path.extname(file));
  return base.trim().replace(/[^\w\-. ]+/g, "-").replace(/\s+/g, "-");
}

async function main() {
  await mkdir(IN, { recursive: true });
  await mkdir(OUT, { recursive: true });

  let files;
  try {
    files = (await readdir(IN)).filter(f => ACCEPTED.has(path.extname(f).toLowerCase()) && !f.startsWith("."));
  } catch {
    files = [];
  }

  if (!files.length) {
    console.log(`No source images found in ${path.relative(process.cwd(), IN)}/`);
    console.log("Put your photos there and run `npm run images` again.");
    return;
  }

  console.log(`Optimising ${files.length} image(s)\n`);
  const manifest = [];
  let before = 0;
  let after = 0;

  for (const file of files) {
    const src = path.join(IN, file);
    const name = safeName(file);
    const input = sharp(src);
    const meta = await input.metadata();
    const srcSize = (await stat(src)).size;
    before += srcSize;

    const written = {};
    for (const size of SIZES) {
      const target = path.join(OUT, `${name}${size.suffix}.webp`);
      const info = await sharp(src)
        .rotate() // honour EXIF orientation from phones
        .resize({ width: size.width, withoutEnlargement: true })
        .webp({ quality: size.quality, effort: 5 })
        .toFile(target);
      written[size.suffix || "full"] = { bytes: info.size, width: info.width };
      after += info.size;
    }

    manifest.push({ name, input: file, source: `${meta.width}x${meta.height}`, ...written });
    const full = written.full.bytes;
    const ratio = full <= srcSize ? `${Math.round((100 * full) / srcSize)}%` : "larger";
    console.log(
      `  ${file.padEnd(28)} ${meta.width}x${meta.height}  ${kB(srcSize).padStart(8)} -> ${kB(full).padStart(7)} (${ratio})`
    );
  }

  const rows = manifest.map(
    m => `| ${m.name} | ${m.source} | ${kB(m.full.bytes)} | ${kB(m["-480"].bytes)} |`
  );

  await writeFile(
    path.join(OUT, "MANIFEST.md"),
    `# Product images\n\nGenerated by \`npm run images\` on ${new Date().toISOString().slice(0, 10)}.\n\n` +
      `| File | Source | 960 px WebP | 480 px WebP |\n| --- | --- | --- | --- |\n${rows.join("\n")}\n`
  );

  const saved = before - after;
  console.log(
    `\nDone. ${files.length} photo(s): ${kB(before)} of originals -> ${kB(after)} of WebP ` +
      `(${Math.round((100 * after) / before)}% of the weight, ${kB(saved)} saved).`
  );
  console.log(`Written to src/assets/products/ — commit those files, not raw-images/.`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
