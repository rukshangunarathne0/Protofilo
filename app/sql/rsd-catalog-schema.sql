-- R.S.D. Premium Watches catalog and private administrator ledger.
-- Public clients can read only ht_products. All operational tables are private;
-- the authenticated Vercel administrator API uses the server-only service role key.

create table if not exists public.ht_products (
  sku text primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  retail_price numeric(12,2) check (retail_price is null or retail_price >= 0),
  stock integer not null default 0 check (stock >= 0),
  reserved integer not null default 0 check (reserved >= 0),
  image text,
  brand text,
  description text,
  trend jsonb not null default '[]'::jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ht_dealers (
  name text primary key,
  email text,
  city text,
  since text,
  status text not null default 'Pending approval',
  terms text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ht_orders (
  id text primary key,
  dealer text not null,
  city text,
  date date not null default current_date,
  amount numeric(12,2) not null default 0 check (amount >= 0),
  units integer not null default 0 check (units >= 0),
  status text not null default 'Submitted',
  channel text,
  delivery text,
  reference text,
  lines jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ht_preorders (
  id text primary key,
  dealer text,
  item text not null,
  units integer not null default 0 check (units >= 0),
  expected text,
  status text not null default 'Awaiting supplier',
  progress numeric(5,4) not null default 0 check (progress >= 0 and progress <= 1),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  name text not null,
  email text,
  phone text,
  rating smallint check (rating is null or rating between 1 and 5),
  message text not null,
  status text not null default 'new' check (status in ('new', 'read')),
  is_dealer boolean not null default false,
  role_label text,
  created_at timestamptz not null default now()
);

create table if not exists public.ht_admin_profile (
  email text primary key,
  name text,
  role text,
  phone text,
  warehouse text,
  prefs jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.ht_products add column if not exists retail_price numeric(12,2);
alter table public.ht_products add column if not exists brand text;
alter table public.ht_products add column if not exists description text;
alter table public.ht_products add column if not exists trend jsonb not null default '[]'::jsonb;
alter table public.ht_products add column if not exists sort_order integer not null default 0;
alter table public.ht_products add column if not exists created_at timestamptz not null default now();
alter table public.ht_products add column if not exists updated_at timestamptz not null default now();

create index if not exists ht_products_sort_idx on public.ht_products (sort_order, sku);
create index if not exists ht_orders_date_idx on public.ht_orders (date desc, id desc);
create index if not exists ht_orders_status_idx on public.ht_orders (status);
create index if not exists ht_preorders_sort_idx on public.ht_preorders (sort_order, id);
create index if not exists feedback_created_idx on public.feedback (created_at desc);

alter table public.ht_products enable row level security;
alter table public.ht_dealers enable row level security;
alter table public.ht_orders enable row level security;
alter table public.ht_preorders enable row level security;
alter table public.feedback enable row level security;
alter table public.ht_admin_profile enable row level security;

drop policy if exists "public catalog read" on public.ht_products;
create policy "public catalog read" on public.ht_products
  for select to anon, authenticated using (true);

-- Do not create anon/authenticated policies for dealer, order, preorder,
-- feedback, or profile tables. The Vercel administrator API uses service_role,
-- which bypasses RLS after validating the HttpOnly R.S.D. session.

grant select on public.ht_products to anon, authenticated;
revoke all on public.ht_dealers, public.ht_orders, public.ht_preorders, public.feedback, public.ht_admin_profile from anon, authenticated;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
security invoker
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists ht_products_touch_updated_at on public.ht_products;
create trigger ht_products_touch_updated_at
before update on public.ht_products
for each row execute function public.touch_updated_at();

drop trigger if exists ht_dealers_touch_updated_at on public.ht_dealers;
create trigger ht_dealers_touch_updated_at
before update on public.ht_dealers
for each row execute function public.touch_updated_at();

drop trigger if exists ht_orders_touch_updated_at on public.ht_orders;
create trigger ht_orders_touch_updated_at
before update on public.ht_orders
for each row execute function public.touch_updated_at();

drop trigger if exists ht_preorders_touch_updated_at on public.ht_preorders;
create trigger ht_preorders_touch_updated_at
before update on public.ht_preorders
for each row execute function public.touch_updated_at();

create or replace function public.ht_place_order(p_order jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.ht_orders (id, dealer, city, date, amount, units, status, channel, delivery, reference, lines)
  values (
    p_order->>'id', p_order->>'dealer', p_order->>'city',
    coalesce((p_order->>'date')::date, current_date),
    coalesce((p_order->>'amount')::numeric, 0), coalesce((p_order->>'units')::integer, 0),
    coalesce(p_order->>'status', 'Submitted'), p_order->>'channel', p_order->>'delivery',
    p_order->>'reference', coalesce(p_order->'lines', '[]'::jsonb)
  )
  on conflict (id) do nothing;
end;
$$;

create or replace function public.ht_set_order_status(p_id text, p_status text)
returns void language sql security definer set search_path = public as $$
  update public.ht_orders set status = p_status where id = p_id;
$$;

create or replace function public.ht_adjust_stock(p_sku text, p_delta integer)
returns void language sql security definer set search_path = public as $$
  update public.ht_products
  set stock = greatest(0, stock + p_delta)
  where sku = p_sku;
$$;

create or replace function public.ht_reset_ledger()
returns void language plpgsql security definer set search_path = public as $$
begin
  truncate table public.ht_orders, public.ht_preorders, public.ht_dealers, public.feedback, public.ht_admin_profile;
  update public.ht_products set reserved = 0, updated_at = now();
end;
$$;

revoke all on function public.ht_place_order(jsonb), public.ht_set_order_status(text, text), public.ht_adjust_stock(text, integer), public.ht_reset_ledger() from public, anon, authenticated;
grant execute on function public.ht_place_order(jsonb), public.ht_set_order_status(text, text), public.ht_adjust_stock(text, integer), public.ht_reset_ledger() to service_role;

