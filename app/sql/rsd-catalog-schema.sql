drop policy if exists "public catalog read" on public.ht_products;
create policy "public catalog read" on public.ht_products
  for select to anon, authenticated using (true);

-- Do not create anon/authenticated policies for dealer, order, feedback,
-- profile, cost, or favourite tables. The Vercel administrator API uses service_role,
-- which bypasses RLS after validating the HttpOnly R.S.D. session.

revoke all on public.ht_products, public.ht_dealers, public.ht_orders, public.feedback, public.ht_admin_profile, public.ht_product_costs, public.ht_product_favorites from anon, authenticated;
grant select on public.ht_products to anon, authenticated;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
security invoker
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists ht_products_touch_updated_at on public.ht_products;
create trigger ht_products_touch_updated_at
before update on public.ht_products
for each row execute function public.touch_updated_at();

drop trigger if exists ht_dealers_touch_updated_at on public.ht_dealers;
create trigger ht_dealers_touch_updated_at
before update on public.ht_dealers
for each row execute function public.touch_updated_at();

drop trigger if exists ht_orders_touch_updated_at on public.ht_orders;
create trigger ht_orders_touch_updated_at
before update on public.ht_orders
for each row execute function public.touch_updated_at();

create or replace function public.ht_place_order(p_order jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.ht_orders (id, dealer, city, date, amount, units, status, channel, delivery, reference, lines)
  values (
    p_order->>'id', p_order->>'dealer', p_order->>'city',
    coalesce((p_order->>'date')::date, current_date),
    coalesce((p_order->>'amount')::numeric, 0), coalesce((p_order->>'units')::integer, 0),
    coalesce(p_order->>'status', 'Submitted'), p_order->>'channel', p_order->>'delivery',
    p_order->>'reference', coalesce(p_order->'lines', '[]'::jsonb)
  )
  on conflict (id) do nothing;
end;
$$;

create or replace function public.ht_set_order_status(p_id text, p_status text)
returns void language sql security definer set search_path = public as $$
  update public.ht_orders set status = p_status where id = p_id;
$$;

create or replace function public.ht_adjust_stock(p_sku text, p_delta integer)
returns void language sql security definer set search_path = public as $$
  update public.ht_products
  set stock = greatest(0, stock + p_delta)
  where sku = p_sku;
$$;

create or replace function public.ht_reset_ledger()
returns void language plpgsql security definer set search_path = public as $$
begin
  truncate table public.ht_orders, public.ht_dealers, public.feedback, public.ht_admin_profile;
  update public.ht_products set reserved = 0, updated_at = now();
end;
$$;

revoke all on function public.ht_place_order(jsonb), public.ht_set_order_status(text, text), public.ht_adjust_stock(text, integer), public.ht_reset_ledger() from public, anon, authenticated;
grant execute on function public.ht_place_order(jsonb), public.ht_set_order_status(text, text), public.ht_adjust_stock(text, integer), public.ht_reset_ledger() to service_role;

