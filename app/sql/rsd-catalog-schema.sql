alter table public.ht_orders drop constraint if exists ht_orders_status_check;
alter table public.ht_orders add constraint ht_orders_status_check check (status in ('Submitted', 'Confirmed', 'Packing', 'Ready', 'Completed'));

create table if not exists public.ht_product_costs (
  sku text primary key references public.ht_products(sku) on delete cascade,
  supplier_price numeric(12,2) not null check (supplier_price >= 0),
  markup_percent numeric(7,2) check (markup_percent is null or (markup_percent >= 0 and markup_percent <= 500)),
  updated_at timestamptz not null default now()
);

create table if not exists public.ht_product_favorites (
  sku text not null references public.ht_products(sku) on delete cascade,
  visitor_id text not null check (char_length(visitor_id) between 16 and 120),
  created_at timestamptz not null default now(),
  primary key (sku, visitor_id)
);

create index if not exists ht_product_costs_updated_idx on public.ht_product_costs (updated_at desc);
create index if not exists ht_product_favorites_sku_idx on public.ht_product_favorites (sku);

create index if not exists ht_products_sort_idx on public.ht_products (sort_order, sku);
create index if not exists ht_orders_date_idx on public.ht_orders (date desc, id desc);
create index if not exists ht_orders_status_idx on public.ht_orders (status);
create index if not exists feedback_created_idx on public.feedback (created_at desc);

