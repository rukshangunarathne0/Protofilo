-- R.S.D. Premium Watches catalog and private administrator ledger.
-- Public clients can read only ht_products. All operational tables are private;
-- the authenticated Vercel administrator API uses the server-only service role key.

create table if not exists public.ht_products (
  sku text primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  reserved integer not null default 0 check (reserved >= 0),
  image text,
  brand text,
  description text,
  colors jsonb not null default '[]'::jsonb,
  trend jsonb not null default '[]'::jsonb,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop table if exists public.ht_preorders;

create table if not exists public.ht_dealers (
  name text primary key,
  email text,
  city text,
  since text,
  status text not null default 'Pending approval',
  terms text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ht_orders (
  id text primary key,
  dealer text not null,
  city text,
  date date not null default current_date,
  amount numeric(12,2) not null default 0 check (amount >= 0),
  units integer not null default 0 check (units >= 0),
  status text not null default 'Submitted',
  channel text,
  delivery text,
  reference text,
  lines jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  name text not null,
  email text,
  phone text,
  rating smallint check (rating is null or rating between 1 and 5),
  message text not null,
  status text not null default 'new' check (status in ('new', 'read')),
  is_dealer boolean not null default false,
  role_label text,
  created_at timestamptz not null default now()
);

create table if not exists public.ht_admin_profile (
  email text primary key,
  name text,
  role text,
  phone text,
  warehouse text,
  prefs jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

